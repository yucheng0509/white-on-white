# 本平台的演練能為哪些風險類型提供**實測證據**，以及用哪個指標佐證。
# 明確標示能測與不能測，是這個對應表可信的前提——
# 20 項裡只有 5 項是我們量得出來的，其餘必須誠實標為「本演練未涵蓋」。
MEASURABLE: dict[str, str] = {
    "A1": "操控成功率。原文明列「系統操控」，本演練以間接提示注入直接量測其發生率。",
    "A2": "揭露率。模型被影響時是否主動說明，正是「決策過程難以理解或解釋」的可量化面向。",
    "A3": "操控成功率。排序結果偏離職缺條件，即「行為背離開發者原意」。",
    "A8": "操控後的輸出內容。被注入影響的排序理由本身就是「不符事實、具誤導性的內容」。",
    "B6": "多步流程的污染穿透率與操控率。原文提到「環境變化導致行為逐漸偏離原始指令」。",
}


def measurable_codes() -> tuple[str, ...]:
    return tuple(MEASURABLE)


def describe(code: str) -> str:
    r = BY_CODE[code]
    return f"({r.code}) {r.name}：{r.description}"
